"""CuPy filtered backprojection for the small Reckon 3-D pilot.

This is the GPU counterpart of the existing slice-wise
``skimage.transform.iradon(..., interpolation='linear', filter_name='ramp')``
path.  It uses the same vertical-axis parallel-beam model, Ram-Lak filtering,
linear detector interpolation, and MRC storage convention ``(z,y,x)``.
It is intentionally a WBP implementation, not CGLS or a CTF correction.
"""

from __future__ import annotations

import numpy as np
from numpy.typing import ArrayLike


def gpu_reconstruct_wbp(
    stack_tyx: ArrayLike,
    angles_deg: ArrayLike,
    *,
    y_chunk: int = 8,
    z_bounds: tuple[int, int] | None = None,
) -> np.ndarray:
    """Reconstruct a cubic ``(z,y,x)`` volume using CuPy Ram-Lak WBP."""

    import cupy as cp  # type: ignore

    stack = np.asarray(stack_tyx, dtype=np.float32)
    angles = np.asarray(angles_deg, dtype=np.float64)
    if stack.ndim != 3 or stack.shape[1] != stack.shape[2] or stack.shape[1] < 2:
        raise ValueError(f"expected (tilt,y,x) square stack, got {stack.shape}")
    if angles.shape != (stack.shape[0],):
        raise ValueError("one angle is required for every tilt plane")
    if y_chunk < 1:
        raise ValueError("y_chunk must be positive")
    if not np.isfinite(stack).all() or not np.isfinite(angles).all():
        raise ValueError("stack and angles must be finite")

    m, n, _ = stack.shape
    # (tilt,y,x) -> (detector,y,tilt), matching the slice-wise iradon
    # construction used by the CPU implementation.
    projections = cp.asarray(np.transpose(stack, (2, 1, 0)), dtype=cp.float32)
    padded_size = max(64, int(2 ** np.ceil(np.log2(2 * n))))
    # Match skimage.transform.iradon: zero-pad only at the high-index end.
    padded = cp.pad(projections, ((0, padded_size - n), (0, 0), (0, 0)), mode="constant")
    # This is skimage's discrete Ram-Lak construction (_get_fourier_filter),
    # rather than the continuous |f| approximation.  The distinction matters
    # for reproducing the established skimage seed convention.
    odd_positive = np.arange(1, padded_size // 2 + 1, 2, dtype=np.int32)
    odd_negative = np.arange(padded_size // 2 - 1, 0, -2, dtype=np.int32)
    n_sequence = np.concatenate((odd_positive, odd_negative))
    ramp_kernel = np.zeros(padded_size, dtype=np.float64)
    ramp_kernel[0] = 0.25
    ramp_kernel[1::2] = -1.0 / (np.pi * n_sequence) ** 2
    ramp = (2.0 * np.real(np.fft.fft(ramp_kernel))).astype(np.float32).reshape(-1, 1, 1)
    filtered_padded = cp.fft.ifft(cp.fft.fft(padded, axis=0) * cp.asarray(ramp), axis=0).real
    filtered = filtered_padded[:n]

    z_start, z_stop = (0, n) if z_bounds is None else z_bounds
    if not (0 <= z_start < z_stop <= n):
        raise ValueError('Invalid reconstruction Z bounds')
    depth = z_stop - z_start
    radius = n // 2
    x_grid, z_grid = cp.mgrid[z_start:z_stop, :n].astype(cp.float32)
    x_grid -= cp.float32(radius)
    z_grid -= cp.float32(radius)
    volume_xyz = cp.zeros((n, n, depth), dtype=cp.float32)
    angle_radians = cp.asarray(np.deg2rad(angles), dtype=cp.float32)
    scale = np.float32(np.pi / (2.0 * max(m, 1)))
    y_indices = cp.arange(n, dtype=cp.int32)
    for y_start in range(0, n, y_chunk):
        y_stop = min(y_start + y_chunk, n)
        chunk = cp.zeros((depth, n, y_stop - y_start), dtype=cp.float32)
        local_y = y_indices[y_start:y_stop][None, None, :]
        for tilt in range(m):
            # Exact iradon coordinate convention: t = ypr*cos(theta) -
            # xpr*sin(theta), with xpr/ypr generated by mgrid-radius.
            detector = z_grid * cp.cos(angle_radians[tilt]) - x_grid * cp.sin(angle_radians[tilt]) + cp.float32(n // 2)
            detector0 = cp.floor(detector).astype(cp.int32)
            detector1 = cp.clip(detector0 + 1, 0, n - 1)
            detector0 = cp.clip(detector0, 0, n - 1)
            weight = detector - detector0.astype(cp.float32)
            # CuPy returns the detector-grid axes followed by the broadcasted
            # y chunk for this mixed advanced-index expression: (x,z,y).
            left = filtered[detector0[:, :, None], local_y, tilt]
            right = filtered[detector1[:, :, None], local_y, tilt]
            valid = (detector >= 0.0) & (detector <= float(n - 1))
            contribution = (left * (1.0 - weight[:, :, None]) + right * weight[:, :, None]) * valid[:, :, None]
            chunk += contribution
        # ``iradon`` returns (row=xpr, col=ypr).  The CPU seed path stores
        # ``slice.T`` as (x,z), so map chunk axes (xpr,zpr,y) to
        # volume_xyz axes (x,y,z) as (zpr,y,xpr).
        volume_xyz[:, y_start:y_stop, :] = (chunk * scale).transpose(1, 2, 0)
    cp.cuda.Stream.null.synchronize()
    return np.asarray(cp.asnumpy(cp.transpose(volume_xyz, (2, 1, 0))), dtype=np.float32)


_local_geometry_identity = None
_local_geometry_values = None


def _local_backprojection_geometry(angles, n):
    """Reuse exact small-volume interpolation geometry for the current angles."""
    import cupy as cp
    global _local_geometry_identity, _local_geometry_values
    identity = (int(cp.cuda.runtime.getDevice()), n, tuple(angles))
    if identity != _local_geometry_identity:
        radius = n // 2
        x_grid, z_grid = cp.mgrid[:n, :n].astype(cp.float32)
        x_grid -= cp.float32(radius)
        z_grid -= cp.float32(radius)
        radians = cp.asarray(np.deg2rad(angles), dtype=cp.float32)
        values = []
        for tilt in range(len(angles)):
            detector = z_grid * cp.cos(radians[tilt]) - x_grid * cp.sin(radians[tilt]) + cp.float32(radius)
            floor = cp.floor(detector)
            d0 = cp.clip(floor.astype(cp.int32), 0, n - 1)
            d1 = cp.clip(d0 + 1, 0, n - 1)
            values.append((d0, d1, detector - floor, (detector >= 0) & (detector <= n - 1)))
        _local_geometry_identity = identity
        _local_geometry_values = values
    return _local_geometry_values


_local_backproject_kernel = None


def _accumulate_local_projection(filtered, detector0, detector1, weight, inside,
                                 chunk, tilt, y_start):
    """Gather and accumulate without changing float32 rounding or tilt order."""
    import cupy as cp
    global _local_backproject_kernel
    if _local_backproject_kernel is None:
        _local_backproject_kernel = cp.ElementwiseKernel(
            'raw float32 plane, raw int32 d0, raw int32 d1, raw float32 weight, '
            'raw bool inside, int32 tilts, '
            'int32 n, int32 width, int32 tilt, int32 y_start',
            'float32 accum',
            r"""
            long long yy = i % width + y_start;
            long long pixel = (i / width) % (n * n);
            long long batch = i / (width * n * n);
            long long base = batch * n * n * tilts + yy * tilts + tilt;
            float left = plane[base + d0[pixel] * n * tilts];
            float right = plane[base + d1[pixel] * n * tilts];
            float w = weight[pixel];
            float value = __fadd_rn(__fmul_rn(left, __fsub_rn(1.0f, w)),
                                   __fmul_rn(right, w));
            accum = __fadd_rn(accum, __fmul_rn(value, (float)inside[pixel]));
            """, 'greco_local_backproject', options=('--fmad=false',))
    _local_backproject_kernel(filtered, detector0, detector1, weight, inside,
                              filtered.shape[3], filtered.shape[1], chunk.shape[-1],
                              tilt, y_start, chunk)


def _gpu_reconstruct_wbp_batch_device(
    stacks_btyx: ArrayLike,
    angles_deg: ArrayLike,
    *,
    valid_bt: ArrayLike | None = None,
    y_chunk: int = 8,
) :
    """Reconstruct many local volumes and keep ``(batch,z,y,x)`` on device.

    Invalid projections contribute exactly zero. Each batch item is scaled by
    its own number of valid views, reproducing an independent WBP call on that
    subset. The output convention is ``(batch,z,y,x)``.
    """
    import cupy as cp  # type: ignore

    stacks = cp.asarray(stacks_btyx, dtype=cp.float32)
    angles = np.asarray(angles_deg, dtype=np.float64)
    if stacks.ndim != 4 or stacks.shape[2] != stacks.shape[3] or stacks.shape[2] < 2:
        raise ValueError(f"expected (batch,tilt,y,x) square stacks, got {stacks.shape}")
    if angles.shape != (stacks.shape[1],) or y_chunk < 1:
        raise ValueError("angles or y_chunk mismatch")
    valid = cp.ones(stacks.shape[:2], dtype=cp.bool_) if valid_bt is None else cp.asarray(valid_bt, dtype=cp.bool_)
    if valid.shape != stacks.shape[:2] or bool(cp.any(valid.sum(axis=1) < 1)):
        raise ValueError("every batch item needs at least one valid projection")
    if not bool(cp.isfinite(stacks).all()) or not np.isfinite(angles).all():
        raise ValueError("stacks and angles must be finite")

    batch, tilts, n, _ = stacks.shape
    projections = stacks.transpose(0, 3, 2, 1)
    projections *= valid[:, None, None, :]
    padded_size = max(64, int(2 ** np.ceil(np.log2(2 * n))))
    padded = cp.pad(projections, ((0, 0), (0, padded_size - n), (0, 0), (0, 0)), mode="constant")
    odd_positive = np.arange(1, padded_size // 2 + 1, 2, dtype=np.int32)
    odd_negative = np.arange(padded_size // 2 - 1, 0, -2, dtype=np.int32)
    sequence = np.concatenate((odd_positive, odd_negative))
    kernel = np.zeros(padded_size, dtype=np.float64)
    kernel[0] = 0.25
    kernel[1::2] = -1.0 / (np.pi * sequence) ** 2
    ramp = cp.asarray((2 * np.real(np.fft.fft(kernel))).astype(np.float32))[None, :, None, None]
    filtered = cp.fft.ifft(cp.fft.fft(padded, axis=1) * ramp, axis=1).real[:, :n]

    radius = n // 2
    x_grid, z_grid = cp.mgrid[:n, :n].astype(cp.float32)
    x_grid -= cp.float32(radius)
    z_grid -= cp.float32(radius)
    angle_radians = cp.asarray(np.deg2rad(angles), dtype=cp.float32)
    scales = cp.asarray(np.pi / (2 * valid.sum(axis=1)), dtype=cp.float32)
    output_xyz = cp.zeros((batch, n, n, n), dtype=cp.float32)
    geometry = _local_backprojection_geometry(angles, n) if n <= 64 else None
    if n <= 64:
        y_chunk = n
    for y_start in range(0, n, y_chunk):
        y_stop = min(y_start + y_chunk, n)
        width = y_stop - y_start
        chunk = cp.zeros((batch, n, n, width), dtype=cp.float32)
        for tilt in range(tilts):
            if geometry is not None:
                detector0, detector1, weight, inside = geometry[tilt]
            else:
                detector = z_grid * cp.cos(angle_radians[tilt]) - x_grid * cp.sin(angle_radians[tilt]) + cp.float32(radius)
                detector_floor = cp.floor(detector)
                detector0 = cp.clip(detector_floor.astype(cp.int32), 0, n - 1)
                detector1 = cp.clip(detector0 + 1, 0, n - 1)
                weight = detector - detector_floor
                inside = (detector >= 0) & (detector <= n - 1)
            if n <= 64:
                _accumulate_local_projection(filtered, detector0, detector1, weight,
                                             inside, chunk, tilt, y_start)
            else:
                plane = filtered[:, :, y_start:y_stop, tilt]
                left = cp.take(plane, detector0.ravel(), axis=1).reshape(batch, n, n, width)
                right = cp.take(plane, detector1.ravel(), axis=1).reshape(batch, n, n, width)
                chunk += (left * (1 - weight[None, :, :, None]) + right * weight[None, :, :, None]) * inside[None, :, :, None]
        output_xyz[:, :, y_start:y_stop, :] = (chunk * scales[:, None, None, None]).transpose(0, 2, 3, 1)
    return output_xyz.transpose(0, 3, 2, 1)


def gpu_batch_size(count, bytes_per_item):
    """Bound temporary GPU work using free VRAM plus reusable pool blocks."""
    import cupy as cp
    free,_=cp.cuda.runtime.memGetInfo()
    pool=cp.get_default_memory_pool()
    available=int(free)+int(pool.total_bytes()-pool.used_bytes())
    budget=min(1024**3,max(1,int((available-512*1024**2)*.3)))
    return max(1,min(int(count),budget//max(1,int(bytes_per_item))))


def gpu_reconstruct_wbp_batch_device(stacks_btyx,angles_deg,*,valid_bt=None,y_chunk=8):
    """Same row-independent WBP arithmetic, with bounded FFT temporaries."""
    import cupy as cp
    batch,tilts,n,_=stacks_btyx.shape
    if not batch:
        return _gpu_reconstruct_wbp_batch_device(stacks_btyx,angles_deg,valid_bt=valid_bt,y_chunk=y_chunk)
    padded=max(64,int(2**np.ceil(np.log2(2*n))))
    # Padded input, complex FFT intermediates, output and gather buffers.
    per_item=tilts*padded*n*48+n**3*32
    limit=gpu_batch_size(batch,per_item)
    if limit>=batch:
        try:
            return _gpu_reconstruct_wbp_batch_device(stacks_btyx,angles_deg,valid_bt=valid_bt,y_chunk=y_chunk)
        except cp.cuda.memory.OutOfMemoryError:
            if batch==1:raise
            limit=max(1,batch//2)
            cp.fft.config.get_plan_cache().clear()
            cp.get_default_memory_pool().free_all_blocks()
    output=cp.empty((batch,n,n,n),dtype=cp.float32)
    limit=min(limit,gpu_batch_size(batch,per_item))
    print(f'GPU WBP batches: {batch} columns, at most {limit} per batch',flush=True)
    start=0
    while start<batch:
        stop=min(start+limit,batch)
        try:
            chunk=_gpu_reconstruct_wbp_batch_device(stacks_btyx[start:stop],angles_deg,
                valid_bt=None if valid_bt is None else valid_bt[start:stop],y_chunk=y_chunk)
            output[start:stop]=chunk
            del chunk
            start=stop
        except cp.cuda.memory.OutOfMemoryError:
            if limit==1:raise
            limit=max(1,limit//2)
            cp.fft.config.get_plan_cache().clear()
            cp.get_default_memory_pool().free_all_blocks()
    return output




def _is_impulse_projection_batch(stacks, angles, valid):
    """Recognize the repeated, nonnegative central-row impulse projections."""
    if not (isinstance(stacks, np.ndarray) and stacks.dtype == np.float32
            and stacks.ndim == 4 and stacks.shape[0] > 0 and stacks.shape[1] > 0
            and stacks.shape[2] == stacks.shape[3] and 3 <= stacks.shape[2] <= 63
            and stacks.shape[2] % 2 and stacks.strides[0] == 0
            and isinstance(angles, np.ndarray) and angles.dtype == np.float64
            and angles.shape == (stacks.shape[1],) and np.isfinite(angles).all()
            and isinstance(valid, np.ndarray) and valid.dtype == np.bool_
            and valid.shape == stacks.shape[:2] and np.all(valid.sum(axis=1) > 0)):
        return False
    projections = stacks[0]
    n = projections.shape[1]
    middle = n // 2
    if not projections.flags.c_contiguous:
        return False
    if (np.any(projections[:, :middle, :].view(np.uint32))
            or np.any(projections[:, middle + 1:, :].view(np.uint32))):
        return False
    row = projections[:, middle, :]
    if not np.isfinite(row).all() or np.signbit(row).any():
        return False
    positive = row[row > 0]
    padded = max(64, int(2 ** np.ceil(np.log2(2 * n))))
    return (not np.any(positive < np.finfo(np.float32).tiny)
            and np.max(row) <= np.finfo(np.float32).max / (padded * len(angles) * n))


_impulse_backproject_kernel = None


def _impulse_wbp_batch_host(stacks, angles, valid):
    """Return the same full host PSFs while reconstructing only their Y plane."""
    import cupy as cp
    batch, tilts, n, _ = stacks.shape
    padded = max(64, int(2 ** np.ceil(np.log2(2 * n))))
    # Keep the established conservative row-batch budget and OOM backoff.
    per_item = tilts * padded * n * 48 + n**3 * 32
    limit = gpu_batch_size(batch, per_item)
    output = np.zeros((batch, n, n, n), np.float32)
    start = 0
    while start < batch:
        stop = min(start + limit, batch)
        try:
            plane = _impulse_wbp_plane(stacks[0], angles, valid[start:stop])
            output[start:stop, :, n // 2, :] = plane
            start = stop
        except cp.cuda.memory.OutOfMemoryError:
            if limit == 1:
                raise
            limit = max(1, limit // 2)
            cp.fft.config.get_plan_cache().clear()
            cp.get_default_memory_pool().free_all_blocks()
    return output


_impulse_filter_identity = None
_impulse_filter_value = None


def _impulse_filtered_rows(projections, angles):
    """Keep one device's current immutable impulse-row filtering result."""
    import cupy as cp
    global _impulse_filter_identity, _impulse_filter_value
    n = projections.shape[1]
    row = projections[:, n // 2, :]
    identity = (int(cp.cuda.runtime.getDevice()), n, angles.tobytes(), row.tobytes())
    if identity == _impulse_filter_identity:
        return _impulse_filter_value
    n = projections.shape[1]
    tilts = len(angles)
    rows = projections[:, n // 2:n // 2 + 1, :]
    stacks = cp.asarray(np.broadcast_to(rows[None], (1,) + rows.shape), cp.float32)
    projected = stacks.transpose(0, 3, 2, 1)
    padded_size = max(64, int(2 ** np.ceil(np.log2(2 * n))))
    padded = cp.pad(projected, ((0, 0), (0, padded_size - n), (0, 0), (0, 0)), mode='constant')
    odd_positive = np.arange(1, padded_size // 2 + 1, 2, dtype=np.int32)
    odd_negative = np.arange(padded_size // 2 - 1, 0, -2, dtype=np.int32)
    sequence = np.concatenate((odd_positive, odd_negative))
    ramp_kernel = np.zeros(padded_size, dtype=np.float64)
    ramp_kernel[0] = 0.25
    ramp_kernel[1::2] = -1.0 / (np.pi * sequence) ** 2
    ramp = cp.asarray((2 * np.real(np.fft.fft(ramp_kernel))).astype(np.float32))[None, :, None, None]
    filtered = cp.fft.ifft(cp.fft.fft(padded, axis=1) * ramp, axis=1).real[:, :n]

    filtered = filtered[0, :, 0, :].copy()
    _impulse_filter_identity, _impulse_filter_value = identity, filtered
    return filtered


def _impulse_wbp_plane(projections, angles, valid):
    import cupy as cp
    n = projections.shape[1]
    tilts = len(angles)
    valid_gpu = cp.asarray(valid)
    filtered = _impulse_filtered_rows(projections, angles)
    global _impulse_backproject_kernel
    if _impulse_backproject_kernel is None:
        _impulse_backproject_kernel = cp.ElementwiseKernel(
            'raw float32 plane, raw int32 d0, raw int32 d1, raw float32 weight, '
            'raw bool inside, raw bool valid, int32 tilts, int32 n, int32 tilt',
            'float32 accum',
            r"""
            long long pixel = i % (n * n);
            long long batch = i / (n * n);
            bool usable = valid[batch * tilts + tilt];
            float left = usable ? plane[d0[pixel] * tilts + tilt] : 0.0f;
            float right = usable ? plane[d1[pixel] * tilts + tilt] : 0.0f;
            float w = weight[pixel];
            float value = __fadd_rn(__fmul_rn(left, __fsub_rn(1.0f, w)),
                                   __fmul_rn(right, w));
            accum = __fadd_rn(accum, __fmul_rn(value, (float)inside[pixel]));
            """, 'greco_impulse_backproject', options=('--fmad=false',))
    geometry = _local_backprojection_geometry(angles, n)
    chunk = cp.zeros((len(valid), n, n), cp.float32)
    for tilt, (detector0, detector1, weight, inside) in enumerate(geometry):
        _impulse_backproject_kernel(filtered, detector0, detector1, weight, inside,
                                    valid_gpu, tilts, n, tilt, chunk)
    scales = cp.asarray(np.pi / (2 * valid_gpu.sum(axis=1)), dtype=cp.float32)
    return cp.asnumpy(chunk * scales[:, None, None])




def gpu_reconstruct_wbp_batch(
    stacks_btyx: ArrayLike,
    angles_deg: ArrayLike,
    *,
    valid_bt: ArrayLike | None = None,
    y_chunk: int = 8,
) -> np.ndarray:
    """Compatible host-returning wrapper for batched local WBP."""
    if y_chunk >= 1 and _is_impulse_projection_batch(stacks_btyx, angles_deg, valid_bt):
        return _impulse_wbp_batch_host(stacks_btyx, angles_deg, valid_bt)
    import cupy as cp  # type: ignore

    device = gpu_reconstruct_wbp_batch_device(
        stacks_btyx, angles_deg, valid_bt=valid_bt, y_chunk=y_chunk)
    return np.asarray(cp.asnumpy(device), dtype=np.float32)
